import pandas as pd
import numpy as np

np.random.seed(42)

states = [
    "Punjab", "Haryana", "Uttar Pradesh", "Madhya Pradesh",
    "Maharashtra", "Rajasthan", "Bihar", "West Bengal"
]

crops = [
    "Wheat", "Rice", "Maize", "Cotton", "Sugarcane",
    "Potato", "Soybean", "Pulses"
]

seasons = ["Kharif", "Rabi", "Summer"]

years = list(range(2018, 2024))

data = []

for year in years:
    for state in states:
        for crop in crops:

            area = np.random.randint(5000, 100000)

            base_yield = {
                "Wheat": 3.2,
                "Rice": 2.8,
                "Maize": 2.5,
                "Cotton": 1.8,
                "Sugarcane": 70,
                "Potato": 22,
                "Soybean": 1.4,
                "Pulses": 1.1
            }[crop]

            yield_value = round(
                base_yield * np.random.uniform(0.85, 1.15), 2
            )

            production = round(area * yield_value, 2)

            rainfall = round(np.random.uniform(450, 1200), 1)
            temperature = round(np.random.uniform(18, 34), 1)

            price = round(
                np.random.uniform(1500, 6000), 2
            )

            revenue = round(production * price, 2)

            season = np.random.choice(seasons)

            data.append([
                state,
                crop,
                year,
                season,
                area,
                production,
                yield_value,
                rainfall,
                temperature,
                price,
                revenue
            ])

columns = [
    "State",
    "Crop",
    "Crop_Year",
    "Season",
    "Area_Hectares",
    "Production_Tonnes",
    "Yield_Tonnes_per_Hectare",
    "Rainfall_mm",
    "Temperature_C",
    "Market_Price",
    "Revenue"
]

df = pd.DataFrame(data, columns=columns)

